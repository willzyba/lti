/**
 * CodeCogs Equation Editor as a single LTI 1.3 Advantage tool.
 *
 * One deployment of this server, registered once per platform (see platforms.js), reaches
 * Canvas, Blackboard, Brightspace, Schoology and any other LTI 1.3 platform - instead of a
 * separate native plugin per LMS, which is what the other adapters in this repo are. Built on
 * ltijs (https://github.com/Cvmcosta/ltijs) v7, an actively-maintained open-source LTI 1.3
 * Advantage implementation, rather than hand-rolled OIDC/JWT handling - this is an auth flow,
 * and that is not a place to prefer bespoke code over a maintained library. v7 is a full
 * TypeScript rewrite of the older, much more widely-documented v5 API; where this file's
 * comments explain a choice, it is usually because v7 changed something v5 tutorials
 * (including whatever an LLM's training data mostly remembers) still describe differently -
 * see README.md's "Verified against" section for exactly what was checked against the
 * installed package's own .d.ts files versus assumed.
 *
 * Two launch shapes, both served the same view (views/launch.html, the same EqEditor UI as
 * every other adapter):
 *
 *   - Deep Linking launch: the instructor opened this tool from a content picker ("Insert
 *     from App") to choose what gets embedded into a page, assignment or announcement. The
 *     UI's "Insert" step here posts to /insert, which returns an auto-submitting form
 *     carrying an LTI Deep Linking response - the platform receives it and embeds the
 *     equation into whatever it was being placed into.
 *   - Resource Link launch: the tool was added as a persistent placement (e.g. a course
 *     navigation link) rather than opened from a content picker. There is nothing to hand
 *     back to the platform in that case; /insert just shows the rendered image to copy.
 *
 * Requires a MongoDB instance (ltijs' platform/session store) - see .env.example. Unlike v5,
 * v7 needs no separate encryption key for a fresh installation: each platform gets its own
 * RSA keypair, generated by platformManager.registerPlatform() and stored in Mongo.
 */

require( 'dotenv' ).config();

var fs = require( 'fs' );
var path = require( 'path' );
var { Provider, HttpMethod } = require( 'ltijs' );
var platforms = require( './platforms' );

if ( !process.env.MONGO_URL ) {
    console.error( 'eqneditor-lti: MONGO_URL is not set - see .env.example.' );
    process.exit( 1 );
}

var provider = new Provider( {
    database: { url: process.env.MONGO_URL },
    server: {
        port: process.env.PORT ? Number( process.env.PORT ) : 3000
    },
    routes: {
        loginRoute: '/login',
        launchRoute: '/launch',
        keysetRoute: '/keys'
    }
} );

var launchTemplate = fs.readFileSync( path.join( __dirname, '..', 'views', 'launch.html' ), 'utf8' );

function escapeHtml( s ) {
    return String( s )
        .replace( /&/g, '&amp;' ).replace( /</g, '&lt;' )
        .replace( />/g, '&gt;' ).replace( /"/g, '&quot;' );
}

// EQNEDITOR_DESIGN is JSON; anything that does not parse is treated as no design at all, so a
// typo leaves the standard editor rather than a broken one.
function parseDesign( json ) {
    try {
        return JSON.parse( json || '{}' ) || {};
    } catch ( e ) {
        return {};
    }
}

function renderLaunchPage( ltik ) {
    // The one thing the static template needs from the server: the ltik that identifies this
    // launch, so the client's later /config and /insert calls can resume it via
    // Provider.getLaunchContext(). JSON.stringify both quotes it and escapes anything that
    // would otherwise break out of the string literal.
    return launchTemplate.replace( '"__LTIK__"', JSON.stringify( ltik ) );
}

async function handleLaunch( context, request, response ) {
    response.html( renderLaunchPage( context.ltik ) );
}

provider.onResourceLink( handleLaunch );
provider.onDeepLinking( handleLaunch );

// Read by views/launch.html on load, so it can tell a Deep Linking launch (Insert should
// return a Deep Linking response) from a Resource Link launch (Insert has nothing to send
// back), and to carry through the render/server hosts this deployment is configured with.
provider.httpHandler.registerRoute( '/config', [ HttpMethod.Get ], async function ( request, response ) {
    var ltik = request.query.ltik;
    if ( !ltik || typeof ltik !== 'string' ) {
        response.status( 400 ).json( { error: 'Missing ltik.' } );
        return;
    }

    var context;
    try {
        context = await provider.getLaunchContext( ltik );
    } catch ( err ) {
        response.status( 401 ).json( { error: 'Launch expired or invalid: ' + err.message } );
        return;
    }

    response.json( {
        isDeepLinking: context.deepLinking.isAvailable(),
        server: process.env.EQNEDITOR_SERVER || 'fxtex.codecogs.com',
        renderUrl: process.env.EQNEDITOR_RENDER_URL || 'https://latex.codecogs.com',
        // Passed straight to EqEditor.init() - an empty licence is the normal, expected state
        // until a real one is configured, not a required variable.
        licence: process.env.EQNEDITOR_LICENCE || '',
        // How the editor looks, as JSON - see the `design` option in the README.
        design: parseDesign( process.env.EQNEDITOR_DESIGN ),
        // The maths view is the default and, by far, the more common thing to want on screen -
        // the LaTeX markup view is the opt-in. This is only the fallback for a first-time
        // visitor with no cookie yet - see views/launch.html.
        showLatex: process.env.EQNEDITOR_SHOW_LATEX === 'true'
    } );
} );

// Called once the instructor has built an equation and pressed Insert.
provider.httpHandler.registerRoute( '/insert', [ HttpMethod.Post ], async function ( request, response ) {
    var body = request.body || {};
    var ltik = body.ltik;
    var url = body.url;
    var latex = body.latex;

    if ( !ltik || typeof ltik !== 'string' ) {
        response.status( 400 ).html( '<p>Missing launch token - go back and reopen the tool.</p>' );
        return;
    }
    if ( !url || !latex ) {
        response.status( 400 ).html( '<p>No equation to insert.</p>' );
        return;
    }

    var context;
    try {
        context = await provider.getLaunchContext( ltik );
    } catch ( err ) {
        response.status( 401 ).html( '<p>Launch expired - go back and reopen the tool.</p>' );
        return;
    }

    if ( !context.deepLinking.isAvailable() ) {
        // Resource Link launch: nothing to hand back to the platform. The page is reached by
        // a real form submission (see views/launch.html) so the response has to be a page
        // too, not JSON - there is no script left on the client side to read JSON with once
        // the browser has already navigated here.
        response.html(
            '<!doctype html><meta charset="utf-8">' +
            '<p style="font-family:sans-serif">Equation ready - copy the image address below ' +
            'into your content, or use <em>Insert from App</em> if this course lets you place ' +
            'this tool from a content picker instead.</p>' +
            '<p><img src="' + url + '" alt="' + escapeHtml( latex ) + '"></p>' +
            '<p><code>' + escapeHtml( url ) + '</code></p>'
        );
        return;
    }

    try {
        var items = [ {
            type: 'html',
            html: '<img src="' + url + '" alt="' + escapeHtml( latex ) + '">'
        } ];

        var form = await context.deepLinking.createDeepLinkingForm( items, {
            message: 'Equation inserted.'
        } );

        response.html( form );
    } catch ( err ) {
        console.error( 'eqneditor-lti: could not build Deep Linking response: ' + err.message );
        response.status( 500 ).html( '<p>Could not send the equation back to the platform.</p>' );
    }
} );

async function main() {
    // listen() connects the database before starting the HTTP listener; platformManager
    // needs that connection, so platforms can only be registered after it, not before.
    await provider.listen();
    console.log( 'eqneditor-lti: listening on port ' + ( process.env.PORT || 3000 ) );
    await platforms.registerPlatforms( provider );
}

main().catch( function ( err ) {
    console.error( 'eqneditor-lti: failed to start: ' + err.message );
    process.exit( 1 );
} );
